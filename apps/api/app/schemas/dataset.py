
"""NUMPA v2 — Dataset API schemas.

Pydantic models for dataset uploads, profiling and previews.
These schemas define the contract between FastAPI and Next.js.
"""

from typing import Any

from pydantic import BaseModel, Field


class NumericStatistics(BaseModel):
    """Summary statistics for a numeric column."""

    mean: float | None = None
    median: float | None = None
    std: float | None = None
    min: float | None = None
    max: float | None = None


class TopValue(BaseModel):
    """One frequently occurring value in a column."""

    value: Any
    count: int = Field(ge=0)


class ColumnProfile(BaseModel):
    """Data quality and statistics for one dataset column."""

    name: str
    dtype: str
    detected_type: str

    missing_count: int = Field(ge=0)
    missing_percentage: float = Field(ge=0, le=100)

    non_null_count: int = Field(ge=0)
    unique_count: int = Field(ge=0)

    # Numeric and categorical columns have different summaries.
    statistics: NumericStatistics | None = None
    top_values: list[TopValue] | None = None


class DatasetOverview(BaseModel):
    """Dataset-wide statistics displayed in NUMPA."""

    rows: int = Field(ge=0)
    columns: int = Field(ge=0)
    total_cells: int = Field(ge=0)

    missing_cells: int = Field(ge=0)
    missing_percentage: float = Field(ge=0, le=100)

    duplicate_rows: int = Field(ge=0)
    duplicate_percentage: float = Field(ge=0, le=100)

    memory_usage_bytes: int = Field(ge=0)


class DatasetProfile(BaseModel):
    """Complete dataset profile generated by the analysis engine."""

    overview: DatasetOverview
    columns: list[ColumnProfile]

    # Each preview record maps column names to JSON-safe values.
    preview: list[dict[str, Any]]


class DatasetUploadResponse(BaseModel):
    """Response returned after successfully uploading a dataset."""

    dataset_id: str = Field(
        description="Unique identifier assigned to the dataset."
    )

    filename: str = Field(
        description="Original uploaded filename."
    )

    file_size_bytes: int = Field(ge=0)

    status: str = Field(
        default="ready",
        description="Dataset processing status."
    )

    profile: DatasetProfile


class DatasetListItem(BaseModel):
    """Compact dataset information for the datasets dashboard."""

    dataset_id: str
    filename: str

    rows: int = Field(ge=0)
    columns: int = Field(ge=0)

    file_size_bytes: int = Field(ge=0)

    created_at: str


class DatasetListResponse(BaseModel):
    """Response containing the user's available datasets."""

    datasets: list[DatasetListItem]
    total: int = Field(ge=0)


class DatasetErrorResponse(BaseModel):
    """Consistent error response for dataset operations."""

    detail: str
