
"""NUMPA v2 - Cleaning execution history storage.

Provides thread-safe, temporary storage for cleaning
execution reports.

Important:
- Execution reports are stored in memory.
- Data is lost when the backend process restarts.
- Every stored and returned report is deep-copied.
- Authentication and persistent storage will be added
  in a later development phase.
"""

from __future__ import annotations

from copy import deepcopy
from datetime import datetime, timezone
from threading import RLock
from typing import Any


# ---------------------------------------------------------
# Storage configuration
# ---------------------------------------------------------

MAX_EXECUTIONS = 200

# A single lock protects all reads and writes.
_execution_lock = RLock()

# Execution ID -> stored execution record.
_executions: dict[str, dict[str, Any]] = {}


# ---------------------------------------------------------
# Storage exceptions
# ---------------------------------------------------------

class ExecutionNotFoundError(LookupError):
    """Raised when an execution ID does not exist."""


class ExecutionAlreadyExistsError(ValueError):
    """Raised when an execution ID is already stored."""


class ExecutionStorageLimitError(ValueError):
    """Raised when the execution store reaches capacity."""


# ---------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------

def _utc_now() -> str:
    """Return an ISO 8601 UTC timestamp."""

    return datetime.now(
        timezone.utc
    ).isoformat()


def _validate_execution(
    execution: dict[str, Any],
) -> str:
    """Validate the minimum required execution metadata."""

    if not isinstance(execution, dict):
        raise TypeError(
            "Execution report must be a dictionary."
        )

    execution_id = execution.get(
        "execution_id"
    )

    if (
        not isinstance(execution_id, str)
        or not execution_id.strip()
    ):
        raise ValueError(
            "Execution report requires a valid execution_id."
        )

    status = execution.get(
        "status"
    )

    if (
        not isinstance(status, str)
        or not status.strip()
    ):
        raise ValueError(
            "Execution report requires a valid status."
        )

    return execution_id.strip()


def _metadata(
    execution: dict[str, Any],
) -> dict[str, Any]:
    """Create a lightweight history-list entry."""

    return {
        "execution_id": execution["execution_id"],
        "status": execution.get("status"),
        "mode": execution.get("mode"),
        "pipeline_name": execution.get(
            "pipeline_name"
        ),
        "dataset_id": execution.get(
            "dataset_id",
            execution.get("original_dataset_id"),
        ),
        "cleaned_dataset_id": execution.get(
            "cleaned_dataset_id"
        ),
        "executed_at": execution.get(
            "executed_at"
        ),
        "stored_at": execution.get(
            "stored_at"
        ),
    }


# ---------------------------------------------------------
# Public storage functions
# ---------------------------------------------------------

def save_execution(
    execution: dict[str, Any],
) -> dict[str, Any]:
    """Store a completed cleaning execution report.

    The execution ID must be unique. Existing records
    cannot be silently overwritten because that would
    compromise the recorded execution history.

    Returns:
        A deep copy of the stored report.
    """

    execution_id = _validate_execution(
        execution
    )

    # Copy the report before storing it so that
    # subsequent caller modifications cannot alter
    # the saved execution history.
    stored = deepcopy(execution)

    stored["execution_id"] = execution_id

    # The storage timestamp is generated by the server,
    # rather than accepted from the submitted report.
    stored["stored_at"] = _utc_now()

    with _execution_lock:
        if execution_id in _executions:
            raise ExecutionAlreadyExistsError(
                f"Execution '{execution_id}' already exists."
            )

        if len(_executions) >= MAX_EXECUTIONS:
            raise ExecutionStorageLimitError(
                "Cleaning execution storage is full."
            )

        _executions[execution_id] = stored

        return deepcopy(stored)


def get_execution(
    execution_id: str,
) -> dict[str, Any]:
    """Retrieve a stored execution report by ID."""

    if (
        not isinstance(execution_id, str)
        or not execution_id.strip()
    ):
        raise ValueError(
            "A valid execution_id is required."
        )

    with _execution_lock:
        execution = _executions.get(
            execution_id.strip()
        )

        if execution is None:
            raise ExecutionNotFoundError(
                f"Execution '{execution_id}' was not found."
            )

        # Never expose the internal mutable record.
        return deepcopy(execution)


def list_executions(
    *,
    dataset_id: str | None = None,
    limit: int = 50,
    offset: int = 0,
) -> dict[str, Any]:
    """List execution metadata with optional filtering.

    Args:
        dataset_id:
            Optionally filter by the original or cleaned
            dataset ID.

        limit:
            Maximum number of entries to return.

        offset:
            Number of matching entries to skip.
    """

    if not 1 <= limit <= 200:
        raise ValueError(
            "limit must be between 1 and 200."
        )

    if offset < 0:
        raise ValueError(
            "offset cannot be negative."
        )

    with _execution_lock:
        # Take a snapshot while holding the lock.
        records = [
            deepcopy(record)
            for record in _executions.values()
        ]

    if dataset_id is not None:
        records = [
            record
            for record in records
            if (
                record.get("dataset_id") == dataset_id
                or record.get("original_dataset_id")
                == dataset_id
                or record.get("cleaned_dataset_id")
                == dataset_id
            )
        ]

    # Newest stored execution appears first.
    records.sort(
        key=lambda record: record.get(
            "stored_at",
            "",
        ),
        reverse=True,
    )

    total = len(records)

    selected = records[
        offset : offset + limit
    ]

    return {
        "executions": [
            _metadata(record)
            for record in selected
        ],
        "total": total,
        "limit": limit,
        "offset": offset,
    }


def delete_execution(
    execution_id: str,
) -> dict[str, Any]:
    """Delete one execution report.

    Deleting a report does not delete its original
    or cleaned datasets.
    """

    if (
        not isinstance(execution_id, str)
        or not execution_id.strip()
    ):
        raise ValueError(
            "A valid execution_id is required."
        )

    with _execution_lock:
        removed = _executions.pop(
            execution_id.strip(),
            None,
        )

        if removed is None:
            raise ExecutionNotFoundError(
                f"Execution '{execution_id}' was not found."
            )

    return {
        "execution_id": execution_id.strip(),
        "deleted": True,
    }


def count_executions() -> int:
    """Return the number of stored execution reports."""

    with _execution_lock:
        return len(_executions)


def clear_execution_history() -> int:
    """Clear the temporary execution store.

    Intended for isolated tests and development only.
    Do not expose this function as a public API endpoint.
    """

    with _execution_lock:
        removed_count = len(_executions)
        _executions.clear()

    return removed_count
